-- Notes
--   • First touch wins everywhere: capture_lead keeps an existing lead
--     attribution, and the webhook only sets users.referred_by_builder_id
--     where it is still null, so Stripe retries and later upgrades never
--     re-attribute a buyer.
--   • A builder's code is never rotated by the app. If one ever has to be
--     retired, deactivate the builder (active = false): capture_lead and the
--     webhook both resolve codes against active builders only.
